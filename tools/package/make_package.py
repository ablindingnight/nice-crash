"""Assemble a Nice Crash tester package under build/package/NiceCrash/ (docs/TESTER_PACKAGE.md).

    python -I tools/package/make_package.py [--python-zip PATH] [--no-upscaler] [--zip] [--dol PATH --disc DIR]

The package holds NO Nintendo data: the tester's own disc is imported on their PC, and the game exe is built there
from the decomp source at the pinned commit plus the port source. What goes in:

  NiceCrash/
    Start Nice Crash.cmd       opens build\\NiceCrash.exe
    README.txt                 the tester's steps
    LICENSES/                  every third-party licence
    build/NiceCrash.exe        launcher (+ import.exe, enhance.exe), compiled now from this checkout
    build/tools/dtk/           decomp-toolkit (disc image reader), copied from the matching repo's build/tools
    build/tools/zig/           zig toolchain (this PC's install, verbatim)
    build/tools/python/        Python embeddable package (from --python-zip; python.org)
    build/tools/realesrgan/    optional AI upscaler (exe, OpenMP dll, the models the launcher uses)
    build/decomp/<pin12>/      the decomp source export at tools/gametrial/decomp_ref.txt, minus src/sdk_mp3
    sdk/ runtime/ shim/ lib/ patches/ assets/ tools/gametrial/   port source as committed at HEAD (git archive)

After assembling, tools/package/scan_package.py checks the folder for anything from the disc or main.dol; the
script fails if it finds any. --dol/--disc give it the developer's own dump to compare against (read only).
"""
import argparse, glob, os, shutil, subprocess, sys, zipfile

HERE = os.path.dirname(os.path.abspath(__file__))
PORT = os.path.normpath(os.path.join(HERE, '..', '..'))
OUT = os.path.join(PORT, 'build', 'package')
PKG = os.path.join(OUT, 'NiceCrash')
sys.path.insert(0, os.path.join(PORT, 'tools', 'gametrial'))
import decomp  # noqa: E402

PORT_DIRS = ['sdk', 'runtime', 'shim', 'lib', 'patches', 'assets', 'tools/gametrial']
# The decomp export minus what the port never builds. src/sdk_mp3's tables were generated from main.dol
# ("Generated by tools/mp3/gentables.py from REXE01 main.dol"), so they must never ship.
DECOMP_EXCLUDE = ['src/sdk_mp3']
UPSCALER_FILES = ['realesrgan-ncnn-vulkan.exe', 'vcomp140.dll']
UPSCALER_MODELS = ['realesrgan-x4plus', 'realesr-animevideov3-x2', 'realesr-animevideov3-x3', 'realesr-animevideov3-x4']


def log(*a):
    print(*a, flush=True)


def copy_tracked():
    """The port source as committed at HEAD (git archive): other sessions' uncommitted edits never ship."""
    import io, tarfile
    tar = subprocess.run(['git', '-C', PORT, 'archive', '--format=tar', 'HEAD', '--', *PORT_DIRS],
                         capture_output=True, check=True).stdout
    with tarfile.open(fileobj=io.BytesIO(tar)) as t:
        n = len([m for m in t.getmembers() if m.isfile()])
        t.extractall(PKG, filter='data')
    head = subprocess.run(['git', '-C', PORT, 'rev-parse', '--short', 'HEAD'], capture_output=True, text=True).stdout
    log('port source        %d files at %s' % (n, head.strip()))
    dirty = subprocess.run(['git', '-C', PORT, 'status', '--porcelain', '--', 'host', 'lib', 'build.sh',
                            'tools/import', 'tools/enhance', 'assets/icon'], capture_output=True, text=True).stdout
    if dirty.strip():
        log('WARNING: the launcher is compiled from the working tree, which has uncommitted changes:\n' + dirty)


def copy_decomp():
    src = decomp.root()  # exports the pinned commit first if this checkout lacks it
    ref = decomp.ref()
    if ref == 'live':
        sys.exit('make_package: tools/gametrial/decomp_ref.txt must pin a commit (not live)')
    dst = os.path.join(PKG, 'build', 'decomp', ref[:12])
    skip = {os.path.normpath(os.path.join(src, p)) for p in DECOMP_EXCLUDE}
    n = 0
    for d, dirs, files in os.walk(src):
        dirs[:] = [x for x in dirs if os.path.normpath(os.path.join(d, x)) not in skip]
        for f in files:
            s = os.path.join(d, f)
            t = os.path.join(dst, os.path.relpath(s, src))
            os.makedirs(os.path.dirname(t), exist_ok=True)
            shutil.copy2(s, t)
            n += 1
    lic = os.path.join(decomp.LIVE, 'LICENSE')
    if os.path.exists(lic):  # CC0 1.0: the decomp's own licence
        shutil.copy2(lic, os.path.join(PKG, 'LICENSES', 'decomp-CC0.txt'))
    log('decomp %s   %d files (without %s)' % (ref[:12], n, ', '.join(DECOMP_EXCLUDE)))


def build_launcher():
    out = os.path.join(PKG, 'build')
    os.makedirs(out, exist_ok=True)
    sh = shutil.which('sh') or r'C:\Program Files\Git\bin\sh.exe'
    r = subprocess.run([sh, os.path.join(PORT, 'build.sh')], cwd=PORT, capture_output=True, text=True,
                       env=dict(os.environ, NICECRASH_OUT=out.replace('\\', '/')))
    if r.returncode:
        sys.exit('make_package: build.sh failed:\n' + r.stdout[-3000:] + r.stderr[-3000:])
    for p in glob.glob(os.path.join(out, '*.pdb')) + glob.glob(os.path.join(out, '*.res')):
        os.remove(p)
    log('launcher           NiceCrash.exe, import.exe, enhance.exe')


def find_zig_dir():
    sys.path.insert(0, os.path.join(PORT, 'tools', 'gametrial'))
    import trial
    return os.path.dirname(trial.find_zig())


def copy_tools(python_zip, upscaler):
    t = os.path.join(PKG, 'build', 'tools')
    dtk = os.path.join(decomp.LIVE, 'build', 'tools', 'dtk.exe')
    os.makedirs(os.path.join(t, 'dtk'), exist_ok=True)
    shutil.copy2(dtk, os.path.join(t, 'dtk', 'dtk.exe'))  # read-only copy from the matching repo
    shutil.copy2(os.path.join(HERE, 'licenses', 'dtk-MIT.txt'), os.path.join(PKG, 'LICENSES', 'dtk-MIT.txt'))
    zd = find_zig_dir()
    shutil.copytree(zd, os.path.join(t, 'zig'))
    shutil.copy2(os.path.join(zd, 'LICENSE'), os.path.join(PKG, 'LICENSES', 'zig-MIT.txt'))
    log('zig                %s' % os.path.basename(zd))
    if python_zip:
        pd = os.path.join(t, 'python')
        with zipfile.ZipFile(python_zip) as z:
            z.extractall(pd)
        shutil.copy2(os.path.join(pd, 'LICENSE.txt'), os.path.join(PKG, 'LICENSES', 'python-PSF.txt'))
        log('python             %s' % os.path.basename(python_zip))
    else:
        log('WARNING: no --python-zip: the package has no Python, so the tester needs Python 3.11+ on PATH')
    if upscaler:
        src = os.path.join(PORT, 'build', 'tools', 'realesrgan')
        if not os.path.exists(os.path.join(src, UPSCALER_FILES[0])):
            log('upscaler           not on this PC, left out (the launcher then scales with Windows\' filter)')
            return
        ud = os.path.join(t, 'realesrgan')
        os.makedirs(os.path.join(ud, 'models'), exist_ok=True)
        for f in UPSCALER_FILES:  # not the demo images/video, not the debug OpenMP dll (not redistributable)
            shutil.copy2(os.path.join(src, f), os.path.join(ud, f))
        for m in UPSCALER_MODELS:
            for ext in ('.bin', '.param'):
                shutil.copy2(os.path.join(src, 'models', m + ext), os.path.join(ud, 'models', m + ext))
        shutil.copy2(os.path.join(HERE, 'licenses', 'realesrgan-MIT.txt'),
                     os.path.join(PKG, 'LICENSES', 'realesrgan-MIT.txt'))
        log('upscaler           Real-ESRGAN ncnn Vulkan + %d models' % len(UPSCALER_MODELS))


def top_files():
    shutil.copy2(os.path.join(HERE, 'README_TESTER.txt'), os.path.join(PKG, 'README.txt'))
    with open(os.path.join(PKG, 'Start Nice Crash.cmd'), 'w', newline='\r\n') as f:
        f.write('@echo off\nstart "" "%~dp0build\\NiceCrash.exe"\n')
    for f in glob.glob(os.path.join(PORT, 'assets', 'fonts', 'OFL-*.txt')):
        shutil.copy2(f, os.path.join(PKG, 'LICENSES', 'fonts-' + os.path.basename(f)))


def dir_size(d):
    return sum(os.path.getsize(os.path.join(r, f)) for r, _, fs in os.walk(d) for f in fs)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--python-zip', help='python-3.x.y-embed-amd64.zip from python.org')
    ap.add_argument('--no-upscaler', action='store_true')
    ap.add_argument('--zip', action='store_true', help='also write build/package/NiceCrash-<date>-<commit>.zip')
    ap.add_argument('--dol', help='your own main.dol, for the scan (read only)')
    ap.add_argument('--disc', help='your own extracted disc folder (DATA), for the scan (read only)')
    a = ap.parse_args()
    if not a.python_zip:
        c = sorted(glob.glob(os.path.join(OUT, '..', 'package-cache', 'python-*-embed-amd64.zip')))
        a.python_zip = c[-1] if c else None
    if os.path.exists(PKG):
        shutil.rmtree(PKG)
    os.makedirs(os.path.join(PKG, 'LICENSES'))
    build_launcher()
    copy_tracked()
    copy_decomp()
    copy_tools(a.python_zip, not a.no_upscaler)
    top_files()
    log('package            %s, %.0f MB' % (PKG, dir_size(PKG) / 1048576))
    scan = [sys.executable, '-I', os.path.join(HERE, 'scan_package.py'), PKG]
    if a.dol:
        scan += ['--dol', a.dol]
    if a.disc:
        scan += ['--disc', a.disc]
    if subprocess.run(scan).returncode:
        sys.exit('make_package: the scan found game data; the package must not be shared')
    if a.zip:
        import datetime
        head = subprocess.run(['git', '-C', PORT, 'rev-parse', '--short=7', 'HEAD'], capture_output=True,
                              text=True).stdout.strip()
        # date + port commit: a tester's bug report names the exact build
        zp = os.path.join(OUT, 'NiceCrash-%s-%s.zip' % (datetime.date.today().isoformat(), head))
        if os.path.exists(zp):
            os.remove(zp)
        with zipfile.ZipFile(zp, 'w', zipfile.ZIP_DEFLATED, compresslevel=6) as z:
            for r, _, fs in os.walk(PKG):
                for f in fs:
                    p = os.path.join(r, f)
                    z.write(p, os.path.relpath(p, OUT))
        log('zip                %s, %.0f MB' % (zp, os.path.getsize(zp) / 1048576))


if __name__ == '__main__':
    main()
